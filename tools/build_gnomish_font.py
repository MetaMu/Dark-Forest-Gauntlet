def polygon(pen,points):
    pen.moveTo(points[0])
    for p in points[1:]: pen.lineTo(p)
    pen.closePath()
def glyph(lines):
    pen=TTGlyphPen(None)
    for line in lines:
        for a,b in zip(line,line[1:]):
            dx,dy=b[0]-a[0],b[1]-a[1];length=math.hypot(dx,dy);nx,ny=-dy/length*34,dx/length*34
            polygon(pen,[(round(a[0]+nx+60),round(a[1]+ny)),(round(a[0]-nx+60),round(a[1]-ny)),(round(b[0]-nx+60),round(b[1]-ny)),(round(b[0]+nx+60),round(b[1]+ny))])
        for x,y in (line[0],line[-1]):
            polygon(pen,[(x+60,y+42),(x+18,y),(x+60,y-42),(x+102,y)])
    return pen.glyph()
